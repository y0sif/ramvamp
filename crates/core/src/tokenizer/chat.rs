    #[test]
    fn sanitizing_a_json_tree_rewrites_strings_and_keys_only() {
        let sanitizer = test_sanitizer();
        let tool = serde_json::json!({
            "<|a|>key": "<a>value",
            "nested": {"list": ["<|abc|>", 1, 2.5, null, true]},
            "clean": "nothing to do",
        });
        let sanitized = sanitizer.sanitize_json(&tool);

        // Structure and scalars survive; every string in the render is clean.
        let rendered = tojson(&sanitized);
        assert!(sanitizer.is_clean(&rendered), "{rendered}");
        assert_eq!(strip_markers(&rendered), tojson(&tool));
        assert!(rendered.contains("2.5") && rendered.contains("null"));
        // ...and the result is still parseable JSON, which is the whole point
        // of rewriting the tree instead of the serialized blob.
        assert_eq!(
            serde_json::from_str::<Value>(&rendered).unwrap()["clean"],
            serde_json::json!("nothing to do")
        );
    }

