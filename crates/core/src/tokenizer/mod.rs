//! Tokenizer and chat-template rendering for installed `.rvmp` models.
//!
//! An install carries the upstream tokenizer verbatim under `tokenizer/`:
//!
//! ```text
//! model.rvmp/
//!   tokenizer/
//!     tokenizer.json           # HF fast-tokenizer definition (~11 MiB)
//!     tokenizer_config.json    # chat template + BOS policy
//!     generation_config.json   # stop tokens + sampling defaults
//! ```
//!
//! [`RvmpTokenizer::load`] reads all three with bounded, offline reads (no
//! network, files capped at [`MAX_TOKENIZER_FILE_BYTES`]) and validates
//! them against the verified architecture facts from
//! `docs/architecture.md`: stop tokens are exactly `{151645 <|im_end|>,
//! 151643 <|endoftext|>}`, the ChatML marker tokens map to their pinned
//! single ids, and BOS is never prepended.
//!
//! Chat rendering does **not** execute the checkpoint's Jinja template; the
//! 2507-Instruct template is vendored as Rust in [`chat`] and
//! snapshot-tested against reference `transformers` renders
//! (`fixtures/chat_fixtures.json`, regenerated by
//! `scripts/gen_tokenizer_fixtures.py`). The Jinja source is still stored
//! ([`RvmpTokenizer::chat_template`]) for provenance.

